// Full production bundle + real ratios reader; simulated native stores on loopback only.
async (page) => {
  if (!/^http:\/\/127\.0\.0\.1:\d+\/fixture$/.test(page.url()) || !await page.evaluate(() => !!window.ratiosFixture)) throw Error("The offline ratios fixture is required.");
  const origin = new URL(page.url()).origin;
  await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  await page.evaluate(() => { localStorage.removeItem('ct-ratios-fixture-main'); localStorage.removeItem('ct-ratios-fixture-alternate'); });
  await page.reload({ waitUntil: 'domcontentloaded' });
  const checks = [];
  const assert = (ok, detail) => { if (!ok) throw Error(detail); checks.push(detail); };
  const wait = fn => page.waitForFunction(fn, null, { polling: 100, timeout: 12000 });
  const idle = () => wait(() => !!document.querySelector('.ct-ratios-add') && !document.querySelector('.ct-ratios-add').disabled);
  const b = name => page.getByRole('button', { name, exact: true });
  const select = async (index, query, symbol, detail = 'ARS · 24 h') => {
    const picker = page.locator('.ct-ratio-picker').nth(index);
    await picker.locator('input').fill(query, { force: true });
    await page.waitForFunction(i => !!document.querySelectorAll('.ct-ratio-picker')[i]?.querySelector('[role=option]'), index, { polling: 100, timeout: 6000 });
    const options = picker.getByRole('option').filter({ hasText: detail });
    const chosen = options.filter({ has: page.locator('strong', { hasText: new RegExp('^' + symbol + '$') }) });
    await chosen.click({ force: true });
  };
  const save = async () => { await page.locator('.ct-ratios button[type=submit]').click({ force: true }); await wait(() => !document.querySelector('.ct-ratios-editor')); await idle(); };
  const addPair = async (a, aSymbol, bb, bSymbol, aDetail, bDetail) => {
    if (!await page.locator('.ct-ratios-editor').count()) await b('Agregar ratio').click({ force: true });
    await select(0, a, aSymbol, aDetail); await select(1, bb, bSymbol, bDetail); await save();
  };
  const snapshot = () => page.evaluate(() => window.mainStore.dashboardStore.currentDashboard.layout.map(w => ({ component: w.component, x: w.x, y: w.y, w: w.w, h: w.h, settings: JSON.parse(JSON.stringify(w.settings)) })));
  const before = await snapshot();
  await idle(); await b('RATIOS · CHUCHOTRIZ').click({ force: true }); await idle();
  await addPair('BMA', 'BMA', 'GGAL', 'GGAL');
  await wait(() => document.querySelector('.ct-ratios-value')?.textContent === '1,090909');
  assert((await page.locator('.ct-ratios tbody tr').first().innerText()).includes('+9,09%'), 'BMA/GGAL uses last prices and exact daily ratio variation');
  await addPair('ALUA', 'ALUA', 'TXAR', 'TXAR');
  await addPair('AL30', 'AL30', 'AL30D', 'AL30D', 'ARS · 24 h', 'USD · 24 h');
  assert(await page.locator('.ct-ratios tbody tr').count() === 3, 'Three independently selected ratios coexist in one widget');
  assert((await page.locator('.ct-ratios tbody tr').nth(2).innerText()).includes('1.400,00'), 'ARS/USD bond ratio divides raw published prices without conversion');
  await page.evaluate(() => window.ratiosFixture.price('BMA-2', 13000));
  await wait(() => document.querySelector('.ct-ratios-value')?.textContent === '1,181818');
  assert(true, 'Quote update refreshes the ratio');
  await b('Invertir BMA/GGAL').click({ force: true }); await idle();
  await wait(() => document.querySelector('.ct-ratios-pair strong')?.textContent === 'GGAL/BMA');
  assert((await page.locator('.ct-ratios tbody tr').first().innerText()).includes('-15,38%'), 'Inverting A/B recomputes the ratio and its daily variation');
  await b('Editar ALUA/TXAR').click({ force: true });
  await select(0, 'AL30', 'AL30', 'ARS · CI'); await save();
  assert((await page.locator('.ct-ratios tbody tr').nth(1).innerText()).includes('ARS · CI'), 'Editing supports a different settlement and preserves its label');
  await b('Agregar ratio').click({ force: true });
  await select(0, 'AL30', 'AL30'); await select(1, 'AL30D', 'AL30D', 'USD · 24 h');
  await page.locator('.ct-ratios button[type=submit]').click({ force: true });
  await wait(() => document.querySelector('.ct-ratios-issue')?.textContent.includes('ya está'));
  assert(await page.locator('.ct-ratios tbody tr').count() === 3, 'Duplicate pairs are rejected without changing the saved table');
  await b('Cancelar').click({ force: true });
  await page.evaluate(() => window.ratiosFixture.price('GGAL-2', undefined));
  await wait(() => document.querySelector('.ct-ratios-value')?.textContent.includes('Sin último precio'));
  assert(true, 'Missing last price is never replaced with a reference or a bid/ask');
  await page.evaluate(() => { window.ratiosFixture.price('GGAL-2', 11000); window.mainStore.securityStore.securities.find(s => s.id === 'GGAL-2').md.refp = undefined; });
  await wait(() => document.querySelector('.ct-ratios tbody tr td:nth-child(5)')?.textContent.includes('Sin referencia diaria'));
  assert(true, 'Missing daily reference hides only the daily variation');
  await page.evaluate(() => window.ratiosFixture.connected(false));
  await wait(() => document.querySelector('.ct-ratios-issue')?.textContent.includes('desconectado'));
  assert((await page.locator('.ct-ratios-value').first().innerText()).includes('Sin último precio'), 'Disconnect clears displayed quote values');
  await page.evaluate(() => { const s = window.mainStore.securityStore.securities.find(s => s.id === 'GGAL-2'); s.md.refp = 10000; s.md.seq = 0; window.ratiosFixture.connected(true); });
  await wait(() => document.querySelector('.ct-ratios-value')?.textContent === '0,846154');
  assert(true, 'Reconnect accepts a reset market sequence');
  await b('Eliminar AL30/AL30D').click({ force: true }); await idle();
  assert(await page.locator('.ct-ratios tbody tr').count() === 2, 'Deleting a pair preserves the other pairs');
  await b('RATIOS · CHUCHOTRIZ').click({ force: true }); await idle();
  assert(await page.locator('.ct-ratios').count() === 2, 'Multiple ratio widgets can be added');
  await page.locator('.ct-ratios').nth(1).getByRole('button', { name: 'Cerrar widget de ratios' }).click({ force: true }); await idle();
  assert(await page.locator('.ct-ratios').count() === 1 && await page.locator('.ct-ratios tbody tr').count() === 2, 'Closing an empty widget does not delete another widget');
  const handle = await b('Redimensionar Ratios').boundingBox();
  await page.mouse.move(handle.x + 10, handle.y + 10); await page.mouse.down(); await page.mouse.move(handle.x + 90, handle.y + 50); await page.mouse.up(); await idle();
  const resized = await snapshot();
  assert(resized.find(w => w.component === 'ChuchoTrizRatiosWidget').w === 840, 'Pointer resize updates the native widget size');
  await page.evaluate(() => window.ratiosFixture.switchDashboard());
  await wait(() => !document.querySelector('.ct-ratios'));
  assert(true, 'Changing dashboards removes the previous dashboard table');
  await page.evaluate(() => window.ratiosFixture.switchDashboard()); await wait(() => !!document.querySelector('.ct-ratios')); await idle();
  await page.reload({ waitUntil: 'domcontentloaded' }); await wait(() => !!document.querySelector('.ct-ratios')); await idle();
  const after = await snapshot();
  assert(JSON.stringify(after) === JSON.stringify(resized), 'Pairs, identity, revisions and geometry persist after a complete reload');
  assert(JSON.stringify(before[0]) === JSON.stringify(after[0]), 'The native control widget remains unchanged');
  await page.screenshot({ path: 'C:/git/ChuchoTriz-ratios-widget/test-results/ratios-widget/simulated.png', animations: 'disabled', timeout: 10000 });
  return { passed: checks.length, checks, before, after, simulated: true, brokerConnection: false };
}
